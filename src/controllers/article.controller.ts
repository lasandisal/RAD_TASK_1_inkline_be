import { Request, Response } from "express"
import { ArticleModel } from "../models/article.model"

const parseTags = (value: unknown): string[] => {
  if (Array.isArray(value)) {
    return value
      .filter((tag): tag is string => typeof tag === "string")
      .map((tag) => tag.trim())
      .filter(Boolean)
  }

  if (typeof value === "string") {
    return value
      .split(",")
      .map((tag) => tag.trim())
      .filter(Boolean)
  }

  return []
}

export const createArticle = async (req: Request, res: Response) => {
  const { title, content, author, tags, createdAt, updatedAt } = req.body

  if (
    typeof title !== "string" ||
    !title.trim() ||
    typeof content !== "string" ||
    !content.trim() ||
    typeof author !== "string" ||
    !author.trim()
  ) {
    return res.status(400).json({
      message: "title, content, and author are required"
    })
  }

  try {
    const imageURL = req.file ? `/uploads/${req.file.filename}` : undefined
    const article = await ArticleModel.create({
      title: title.trim(),
      content: content.trim(),
      author: author.trim(),
      imageURL,
      tags: parseTags(tags)
    })

    return res.status(201).json({
      message: "Article created successfully",
      article,
      data: article,
      ...(createdAt || updatedAt ? { ignoredTimestamps: "createdAt and updatedAt are generated by the server" } : {})
    })
  } catch (error) {
    console.error("Failed to create article", error)
    return res.status(500).json({ message: "Failed to create article" })
  }
}

export const getArticles = async (_req: Request, res: Response) => {
  try {
    const articles = await ArticleModel.find().sort({ createdAt: -1 }).lean()

    return res.status(200).json({ data: articles })
  } catch (error) {
    console.error("Failed to fetch articles", error)
    return res.status(500).json({ message: "Failed to fetch articles" })
  }
}

export const getArticle = async (req: Request, res: Response) => {
  try {
    const article = await ArticleModel.findById(req.params.id).lean()

    if (!article) {
      return res.status(404).json({ message: "Article not found" })
    }

    return res.status(200).json({ data: article })
  } catch (error) {
    console.error("Failed to fetch article", error)
    return res.status(400).json({ message: "Invalid article ID" })
  }
}
